def _load_dotenv(path: str | None = None) -> None:
    """
    فایل .env کنار پروژه رو می‌خونه و متغیرهایی که هنوز ست نشدن رو توی محیط می‌ذاره
    محکم و بدون بلاک: BOM و CRLF و کوتیشن و export و کامنت ته‌خطی تحمل میشه
    اولویت با متغیرهای محیط اصلیه (ریلوِی و systemd اوررایت نمیشن)
    خطای خواندن یا انکد فایل هم بی‌صدا رد میشه، ربات به‌خاطر .env هرگز نمی‌افته
    کلیدهایی که از فایل ست کرده رو تو DOTENV_KEYS نگه می‌داره (bot.py برای لاگ بوت استفاده می‌کنه)
    """
    loaded_from_file = DOTENV_KEYS
    try:
        p = path or os.path.join(os.path.dirname(os.path.abspath(__file__)), ".env")
        if not os.path.isfile(p):
            return
        with open(p, encoding="utf-8-sig") as f:  # utf-8-sig برام BOM رو می‌خوره
            for line in f:
                line = line.strip("\r\n").strip()
                if not line or line.startswith("#"):
                    continue
                if line.startswith("export "):
                    line = line[len("export "):].lstrip()
                if "=" not in line:
                    continue
                key, _, val = line.partition("=")
                key, val = key.strip(), val.strip()
                if len(val) >= 2 and val[0] == val[-1] and val[0] in "\"'":
                    val = val[1:-1]
                elif " #" in val:
                    val = val.split(" #", 1)[0].rstrip()
                if key and val and key not in os.environ:
                    os.environ[key] = val
                    loaded_from_file.append(key)
    except (OSError, UnicodeError):
        pass  # هیچ‌وقت به‌خاطر .env ربات نمی‌افته (راند ۱۷، درخواست کارفرما)


_load_dotenv()

